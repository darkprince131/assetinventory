/**
 * build-supabase-sql.js — generates the Postgres schema from DB.SCHEMA.
 *
 * The nine tables must match the sheet schema column for column, so the SQL is
 * derived from the same source of truth rather than hand-written. Re-run it
 * after any schema change and re-apply the output.
 *
 *   node tools/build-supabase-sql.js
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(ROOT, 'supabase', 'schema.sql');

const TYPES = {
  text: 'text',
  number: 'numeric',
  date: 'date',
  datetime: 'timestamptz',
  bool: 'boolean'
};

/** Loads just enough of the logic to read DB.SCHEMA. */
function loadSchema() {
  const sandbox = {
    console,
    SpreadsheetApp: { getActiveSpreadsheet: () => null, newDataValidation: () => ({}) },
    PropertiesService: { getScriptProperties: () => ({ getProperty: () => null, setProperty: () => {}, deleteProperty: () => {} }) },
    CacheService: { getScriptCache: () => ({ get: () => null, put: () => {}, putAll: () => {} }) },
    LockService: { getScriptLock: () => ({ tryLock: () => true, releaseLock: () => {} }) },
    Session: { getActiveUser: () => ({ getEmail: () => '' }), getEffectiveUser: () => ({ getEmail: () => '' }), getScriptTimeZone: () => 'UTC' },
    Utilities: { formatDate: () => '' },
    HtmlService: {}
  };
  vm.createContext(sandbox);
  fs.readdirSync(SRC).filter(f => f.endsWith('.gs')).sort().forEach(f => {
    vm.runInContext(fs.readFileSync(path.join(SRC, f), 'utf8'), sandbox, { filename: f });
  });
  if (!sandbox.DB || !sandbox.DB.SCHEMA) throw new Error('Could not read DB.SCHEMA from /src');
  return { schema: sandbox.DB.SCHEMA, tabs: sandbox.DB.TABS, seed: sandbox.DB.CONFIG_SEED };
}

function quote(s) { return "'" + String(s).replace(/'/g, "''") + "'"; }

function build() {
  const { schema, tabs, seed } = loadSchema();
  const lines = [];

  lines.push('-- GENERATED by tools/build-supabase-sql.js — do not edit by hand.');
  lines.push('-- Source of truth: DB.SCHEMA in src/Sheets.gs');
  lines.push('--');
  lines.push('-- Run this once in the Supabase SQL editor. Safe to re-run: it only');
  lines.push('-- creates what is missing and never drops a table that holds data.');
  lines.push('');

  tabs.forEach(tab => {
    const spec = schema[tab];
    const table = tab.toLowerCase();
    lines.push('create table if not exists public.' + table + ' (');
    lines.push('  row_id bigint generated always as identity primary key,');
    const cols = spec.cols.map(c => '  ' + c[0] + ' ' + (TYPES[c[1]] || 'text'));
    lines.push(cols.join(',\n'));
    lines.push(');');
    if (spec.id) {
      // Row order is the grid's row order, so reads stay stable and cheap.
      lines.push('create index if not exists ' + table + '_' + spec.id + '_idx on public.' + table +
        ' (lower(' + spec.id + '));');
    }
    lines.push('');
  });

  lines.push('-- Fast lookups the app leans on.');
  lines.push('create index if not exists assets_serial_idx on public.assets (lower(serial_number));');
  lines.push('create index if not exists assets_status_idx on public.assets (status);');
  lines.push('create index if not exists assignments_asset_idx on public.assignments (asset_id);');
  lines.push('create index if not exists maintenance_asset_idx on public.maintenance (asset_id);');
  lines.push('create index if not exists auditlog_entity_idx on public.auditlog (entity_id);');
  lines.push('');

  lines.push('-- The write mutex. One row, updated atomically to claim the lock.');
  lines.push('create table if not exists public._system (');
  lines.push('  id int primary key default 1,');
  lines.push('  token text,');
  lines.push('  locked_at timestamptz,');
  lines.push('  label text,');
  lines.push('  constraint _system_single_row check (id = 1)');
  lines.push(');');
  lines.push('insert into public._system (id) values (1) on conflict (id) do nothing;');
  lines.push('');

  lines.push('-- Sign-in credentials. Kept apart from the Users table so that table');
  lines.push('-- stays exactly the schema the app expects.');
  lines.push('create table if not exists public.auth_credentials (');
  lines.push('  email text primary key,');
  lines.push('  password_hash text not null,');
  lines.push('  must_change boolean not null default true,');
  lines.push('  failed_attempts int not null default 0,');
  lines.push('  locked_until timestamptz,');
  lines.push('  created_at timestamptz not null default now(),');
  lines.push('  updated_at timestamptz not null default now()');
  lines.push(');');
  lines.push('');

  lines.push('-- Every table is reachable only by the service role, which the Netlify');
  lines.push('-- functions hold. Enabling RLS with no policies denies the anon key');
  lines.push('-- outright, so a leaked public key exposes nothing.');
  const all = tabs.map(t => t.toLowerCase()).concat(['_system', 'auth_credentials']);
  all.forEach(t => lines.push('alter table public.' + t + ' enable row level security;'));
  lines.push('');

  lines.push('-- Config seed: the dropdown lists every screen reads from.');
  lines.push('insert into public.config (key, value)');
  const rows = [];
  Object.keys(seed).forEach(key => seed[key].forEach(v => rows.push('  (' + quote(key) + ', ' + quote(v) + ')')));
  lines.push('select * from (values');
  lines.push(rows.join(',\n'));
  lines.push(') as seed(key, value)');
  lines.push('where not exists (select 1 from public.config);');
  lines.push('');

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, lines.join('\n'));
  console.log('Wrote ' + path.relative(ROOT, OUT) + ' — ' + tabs.length + ' tables + _system + auth_credentials, ' +
    rows.length + ' config rows.');
}

build();
